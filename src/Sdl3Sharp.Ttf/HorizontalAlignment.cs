namespace Sdl3Sharp.Ttf;

/// <summary>
/// Represents the horizontal alignment used when rendering wrapped text
/// </summary>
public enum HorizontalAlignment
{
	/// <summary>Represents an invalid alignment</summary>
	Invalid = -1,

	/// <summary>Aligns to the left edge</summary>
	Left,

	/// <summary>Aligns to the horizontal center</summary>
	Center,

	/// <summary>Aligns to the right edge</summary>
	Right,
}
